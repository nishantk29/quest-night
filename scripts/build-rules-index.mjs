// Builds src/rules-index.js from this game's own FAQ (public/js/faq.js), as plain text chunks for "Ask a rule".
// Shared script (source /workspace/code-team/shared/ai/build-rules-index.mjs). Run: node scripts/build-rules-index.mjs
// test/rules-index.test.js fails if the committed index is out of date with the FAQ.
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';

const ENT = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rsquo: '’', lsquo: '‘', ldquo: '“', rdquo: '”', ndash: '–', mdash: '—', hellip: '…', middot: '·', times: '×', minus: '−' };
export const plain = (h) => String(h ?? '').replace(/<svg[\s\S]*?<\/svg>/g, ' ').replace(/<(li|p|br|h3|tr)\b[^>]*>/gi, '\n').replace(/<[^>]+>/g, ' ')
  .replace(/&(#\d+|#x[0-9a-f]+|\w+);/gi, (m, e) => (e[0] === '#' ? String.fromCodePoint(e[1] === 'x' ? parseInt(e.slice(2), 16) : +e.slice(1)) : ENT[e] ?? m))
  .split('\n').map((l) => l.replace(/\s+/g, ' ').trim()).filter(Boolean).join('\n');

export const hashOf = (idx) => createHash('sha256').update(JSON.stringify(idx)).digest('hex').slice(0, 12);

export async function buildIndex(root) {
  const m = await import(pathToFileURL(path.join(root, 'public/js/faq.js')).href);
  const out = [];
  const add = (group, q, text) => { const t = plain(text); if (t) out.push({ id: out.length, group: plain(group), q: plain(q), text: t }); };
  if (Array.isArray(m.FAQ) && Array.isArray(m.FAQ[0])) { // [group, [[q, html], ...]]
    for (const [g, items] of m.FAQ) for (const [q, a] of items) add(g, q, a);
  } else if (Array.isArray(m.FAQ)) { // [{ q, a, steps, list }]
    for (const it of m.FAQ) add('FAQ', it.q, [it.a, ...(it.steps || []).map((s, i) => `${i + 1}. ${s}`), ...(it.list || []).map((s) => `- ${s}`)].filter(Boolean).join('\n'));
  } else if (typeof m.faqScreen === 'function') { // rendered page: <h2> groups, <details><summary>q</summary>answer</details>
    const html = m.faqScreen();
    let group = 'FAQ';
    const re = /<h2\b[^>]*>([\s\S]*?)<\/h2>|<details\b[^>]*>\s*<summary\b[^>]*>([\s\S]*?)<\/summary>([\s\S]*?)<\/details>/g;
    for (let x; (x = re.exec(html));) {
      if (x[1] != null) { group = x[1]; continue; }
      // A long role list becomes one chunk per role, so "what does the Jester do?" finds the Jester.
      if (/<li\b[^>]*data-role=/.test(x[3])) {
        const team = plain(x[2]);
        for (const li of x[3].matchAll(/<li\b[^>]*data-role="[^"]*"[^>]*>([\s\S]*?)<\/li>/g)) {
          const nm = li[1].match(/<b>([\s\S]*?)<\/b>/); if (nm) add(team, nm[1], li[1]);
        }
        continue;
      }
      add(group, x[2], x[3]);
    }
  }
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = process.cwd();
  const idx = await buildIndex(root);
  if (idx.length < 5) { console.error(`rules index too small (${idx.length} chunks)`); process.exit(1); }
  fs.writeFileSync(path.join(root, 'src/rules-index.js'), `// Generated by scripts/build-rules-index.mjs from public/js/faq.js. Do not edit by hand.\nexport const RULES_HASH = '${hashOf(idx)}';\nexport const RULES_INDEX = ${JSON.stringify(idx, null, 1)};\n`);
  console.log(`src/rules-index.js: ${idx.length} chunks`);
  process.exit(0);
}
